//==============================================================================================
// periph_regs - шаблон регистрового интерфейса устройства на шине регистров askoRV32
//==============================================================================================
//DESCRIPTION: Переводит обращения шины (memmux) в стробы по регистрам устройства и собирает
//данные чтения. Правила шины - hw/info/architecture.md, раздел «Шина данных и периферии»:
//  - запись выполняется в такте обращения (стадия M), байтовые стробы Write уже учитывают выбор
//    устройства (sel) - memmux обнуляет их у невыбранных устройств;
//  - Read - строб чтения (загрузка) для регистров с побочным действием: выборка из FIFO, сброс
//    флага чтением; выставляется ровно один раз на загрузку;
//  - данные чтения: MEMORY_TYPE = 1 (BSRAM) - из регистра, на следующем такте; MEMORY_TYPE = 0
//    (синтезированная память) - комбинационно, в том же такте;
//  - ожиданий нет: устройство принимает запись и выдаёт данные за указанное время, всё медленное
//    прячется внутри устройства за флагами «занято / готово».
//Регистры устройства - 32-битные слова по адресам 0x00, 0x04, ..., 4 * (N - 1) от начала окна.
//Номер регистра - биты адреса [AW + 1 : 2]; старшие биты окна не проверяются (регистры
//повторяются по окну). Номера >= N читаются как 0, запись в них игнорируется.
//
//Как сделать устройство (пример - stim_top в periph/simple_timer/tim.sv):
//  1. periph_regs #(.N(<число регистров>), .MEMORY_TYPE(MEMORY_TYPE)) regs (...) - стробы we[i], re[i];
//  2. обычный регистр чтения/записи - periph_reg #(.W(<разрядность>)) с we[i] и wdata;
//  3. особые регистры (флаги, FIFO, команды) - своя логика по we[i] / re[i] / wdata;
//  4. в rdata[i] - значение регистра i для чтения (в 32 бита, лишние биты - 0).
module periph_regs
  #(parameter int N           = 8,          //Число 32-битных регистров устройства
    parameter bit MEMORY_TYPE = 0)          //1 - данные чтения через регистр (BSRAM), 0 - комбинационно
   (input  logic                  clk,
    //Шина регистров (со стороны memmux)
    input  logic           [ 3:0] Write,    //Байтовые стробы записи (с учётом выбора устройства)
    input  logic                  Read,     //Строб чтения (с учётом выбора устройства)
    input  logic           [31:0] Addr,
    input  logic           [31:0] WData,
    output logic           [31:0] RData,
    //Сторона устройства
    output logic [N-1:0]   [ 3:0] we,       //Байтовые стробы записи регистра i
    output logic [N-1:0]          re,       //Строб чтения регистра i
    output logic           [31:0] wdata,
    input  logic [N-1:0]   [31:0] rdata     //Значение регистра i для чтения
);
    localparam int AW = (N > 1) ? $clog2(N) : 1;
    logic [AW-1:0] idx;
    assign idx   = Addr[AW+1:2];
    assign wdata = WData;

    for (genvar i = 0; i < N; i++) begin : g_strobe
        assign we[i] = (idx == AW'(i)) ? Write : 4'b0000;
        assign re[i] = (idx == AW'(i)) & Read;
    end

    logic [31:0] rd;
    always_comb begin
        rd = 32'd0;
        for (int i = 0; i < N; i++)
            if (idx == AW'(i)) rd = rdata[i];
    end

    generate if (MEMORY_TYPE) begin : g_rd_reg      //#1 - Память BSRAM: данные на следующем такте
        always_ff @(posedge clk) RData <= rd;
    end else begin : g_rd_comb                      //#0 - Синтезированная память
        assign RData = rd;
    end
    endgenerate
endmodule

//==============================================================================================
// periph_reg - регистр чтения/записи W бит с байтовыми стробами
//==============================================================================================
//DESCRIPTION: Для обычных регистров настройки: байт b записывается по we[b]. Биты старше W при
//записи отбрасываются (читаются как 0 - при подключении к rdata дополняются нулями).
module periph_reg
  #(parameter int         W    = 32,        //Разрядность регистра (1..32)
    parameter logic [W-1:0] INIT = '0)      //Значение после сброса
   (input  logic         clk, rst,
    input  logic [ 3:0]  we,                //Стробы из periph_regs: we[i]
    input  logic [31:0]  wdata,
    output logic [W-1:0] q
);
    logic [31:0] nxt;
    always_comb begin
        nxt = 32'(q);
        for (int b = 0; b < 4; b++)
            if (we[b]) nxt[8*b +: 8] = wdata[8*b +: 8];
    end
    always_ff @(posedge clk)
        if (rst) q <= INIT;
        else     q <= nxt[W-1:0];
endmodule
