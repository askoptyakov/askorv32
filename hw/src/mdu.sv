//==============================================================================================
// mdu_div - делитель расширения M (div, divu, rem, remu), BPC бит частного за такт
//==============================================================================================
//DESCRIPTION: Шаг деления - алгоритм без восстановления остатка из делителя Ивана Ряскина
//(г. Миасс; модули u_div_slow и u_div_fast): на каждом шаге ОДНО сложение или вычитание делителя по
//знаку частичного остатка, без мультиплексора восстановления. На ПЛИС шаг - одна цепочка ячеек ALU:
//выбор «+D / -D» ложится на вход сумматора. BPC шагов соединены в цепочку за один такт (как в
//u_div_fast, где все шаги - комбинационная цепочка), деление занимает 32 / BPC + 2 такта:
//  старт (модули операндов) -> 32 / BPC тактов шагов -> DONE (коррекция остатка и знаков, результат).
//Результат держится и после DONE, пока не начнётся следующее деление: в конвейере он забирается
//в стадии M (как у умножения), в однотактном ядре - в такте DONE.
//Прерывание во время деления: инструкция гасится, делитель сбрасывается (req = 0 или cancel) и после
//mret деление начинается заново - задержка прерывания не растёт на время деления.
//Число сумматоров растёт пропорционально BPC, путь за такт - тоже (BPC сумматоров подряд).
//
//Управление и особые случаи - как в CORE-V Wally (openhwfoundation/cvw, src/mdu/div.sv):
//  - деление модулей, знак частного = знак(a) ^ знак(b), знак остатка = знак делимого;
//  - деление на 0: частное - все единицы, остаток - делимое (получается из алгоритма при D = 0);
//  - переполнение -2^31 / -1: частное -2^31, остаток 0 (получается из деления модулей).
//
//Шаг без восстановления (R - частичный остаток со знаком, 34 бита: |R| < D < 2^32, 2R + 1 < 2^33):
//  Rs = 2R + очередной бит делимого;  R' = (R < 0) ? Rs + D : Rs - D;  бит частного = (R' >= 0)
//  после 32 шагов: остаток = (R < 0) ? R + D : R.
module mdu_div #(parameter int BPC = 2)       //Бит частного за такт: 1, 2, 4 (32 должно делиться на BPC)
   (input  logic        clk, rst,
    input  logic        req,                 //В стадии E действительная div/rem (держится до done)
    input  logic        cancel,              //Инструкция гасится ловушкой (нужно однотактному ядру)
    input  logic [31:0] a, b,                //Делимое и делитель (после байпаса) - берутся в такте старта
    input  logic        is_signed,           //div, rem
    input  logic        is_rem,              //rem, remu
    output logic        done,                //Результат готов (в этом такте инструкция уходит из стадии E)
    output logic [31:0] result
);
    localparam int STEPS = 32 / BPC;
    typedef enum logic [1:0] {IDLE, BUSY, DONE} state_t;
    state_t state;
    logic [$clog2(STEPS):0] cnt;

    logic [33:0] R;                          //Частичный остаток со знаком
    logic [31:0] Q;                          //Слева - ещё не использованные биты делимого, справа - биты частного
    logic [31:0] D;                          //|делитель|
    logic        neg_q, neg_r, div0, rem_op;

    //#1 Модули операндов на старте
    logic sa, sb;
    assign sa = is_signed & a[31];
    assign sb = is_signed & b[31];

    //#2 BPC шагов за такт
    logic [33:0] r_s [BPC:0];
    logic [31:0] q_s [BPC:0];
    assign r_s[0] = R;
    assign q_s[0] = Q;
    for (genvar i = 0; i < BPC; i++) begin : g_step
        logic [33:0] rs;
        assign rs         = {r_s[i][32:0], q_s[i][31]};
        assign r_s[i + 1] = r_s[i][33] ? rs + {2'b00, D} : rs - {2'b00, D};
        assign q_s[i + 1] = {q_s[i][30:0], ~r_s[i + 1][33]};
    end

    always_ff @(posedge clk)
        if (rst) state <= IDLE;
        else case (state)
            IDLE: if (req & ~cancel) begin
                      R      <= '0;
                      Q      <= sa ? -a : a;
                      D      <= sb ? -b : b;
                      neg_q  <= sa ^ sb;
                      neg_r  <= sa;
                      div0   <= (b == 32'd0);
                      rem_op <= is_rem;
                      cnt    <= '0;
                      state  <= BUSY;
                  end
            BUSY: if (~req | cancel) state <= IDLE;  //Инструкция ушла из стадии E (ловушка, вход в отладку)
                  else begin
                      R   <= r_s[BPC];
                      Q   <= q_s[BPC];
                      cnt <= cnt + 1'b1;
                      if (cnt == STEPS - 1) state <= DONE;
                  end
            default: state <= IDLE;          //DONE: результат выдан, инструкция ушла из стадии E
        endcase

    assign done = (state == DONE);

    //#3 Коррекция остатка и знаков
    logic [31:0] rem_u, quot, rem;
    assign rem_u  = R[33] ? R[31:0] + D : R[31:0];
    assign quot   = div0 ? 32'hFFFF_FFFF : (neg_q ? -Q : Q);
    assign rem    = neg_r ? -rem_u : rem_u;
    assign result = rem_op ? rem : quot;
endmodule

//==============================================================================================
// mdu_mul - умножитель расширения M (mul, mulh, mulhsu, mulhu) на блоках DSP
//==============================================================================================
//DESCRIPTION: Операнды расширяются до 33 бит по знаку (со знаком) или нулём (без знака), и одно
//умножение 33 x 33 со знаком даёт все четыре варианта: mul - младшие 32 бита, mulh* - старшие.
//Синтезатор раскладывает его на умножители MULT18X18 и сумматоры блоков DSP.
//В конвейере операнды защёлкиваются на границе E/M, умножение идёт в стадии M, результат
//защёлкивается на границе M/W (как в CORE-V Wally: умножение занимает стадии E и M).
module mdu_mul
   (input  logic [31:0] a, b,
    input  logic [ 1:0] funct3,              //00 mul, 01 mulh, 10 mulhsu, 11 mulhu
    output logic [31:0] result
);
    logic               sa, sb;
    logic signed [65:0] prod;
    assign sa     = (funct3 != 2'b11);       //mul, mulh, mulhsu: a со знаком
    assign sb     = (funct3 == 2'b01);       //mulh: b со знаком
    assign prod   = $signed({sa & a[31], a}) * $signed({sb & b[31], b});
    assign result = (funct3 == 2'b00) ? prod[31:0] : prod[63:32];
endmodule
